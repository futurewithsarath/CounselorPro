// Generate standard academic programs list for all 31 NITs
export const ALL_NIT_PROGRAMS: NitAcademicProgram[] = (() => {
  const programs: NitAcademicProgram[] = [];
  
  for (const nit of ALL_NITS) {
    // Top-tier NITs have broader branch offerings, newer NITs offer core branches
    const isNewer = ['212', '213', '215', '217', '218', '221', '222'].includes(nit.code);
    const applicableBranches = isNewer
      ? CORE_BRANCHES.slice(0, 5) // Core 5: CSE, ECE, EEE, MECH, CIVIL
      : CORE_BRANCHES.slice(0, 8); // Core 8: + CHEM, MME, BIO

    const extra = SPECIALIZED_PROGRAMS[nit.code] || [];
    const allForNit = [...applicableBranches, ...extra];
    const seenCodes = new Set<string>();

    for (const br of allForNit) {
      if (seenCodes.has(br.code)) continue;
      seenCodes.add(br.code);

      programs.push({
        id: `nit-${nit.code}-${br.code.toLowerCase()}`,
        instituteCode: nit.code,
        instituteName: nit.name,
        instituteShortName: nit.shortName,
        instituteState: nit.state,
        programCode: br.code,
        programName: br.name,
        degree: '4 Years, Bachelor of Technology',
        durationYears: 4
      });
    }
  }

  return programs;
})();

/**
 * Determine whether candidate qualifies for Home State (HS) or Other State (OS)
 * quota at a given NIT, strictly based on the Class XII State Code of Eligibility.
 */
export function determineNitQuota(
  candidateStateOfEligibility: string,
  nitState: string
): 'Home State (HS)' | 'Other State (OS)' {
  if (!candidateStateOfEligibility || !nitState) {
    return 'Other State (OS)';
  }

  // Exact match between candidate's qualifying state and institute's state
  if (candidateStateOfEligibility.trim().toLowerCase() === nitState.trim().toLowerCase()) {
    return 'Home State (HS)';
  }

  // JoSAA official UT mappings where UT has no separate NIT:
  const normalizedCandidate = candidateStateOfEligibility.trim().toLowerCase();
  const normalizedNitState = nitState.trim().toLowerCase();

  // Dadra & Nagar Haveli and Daman & Diu -> NIT Goa (shared Home State quota)
  if (normalizedCandidate.includes('daman') || normalizedCandidate.includes('dadra')) {
    if (normalizedNitState === 'goa') return 'Home State (HS)';
  }

  // Ladakh -> NIT Srinagar (Jammu and Kashmir)
  if (normalizedCandidate === 'ladakh' && normalizedNitState.includes('kashmir')) {
    return 'Home State (HS)';
  }

  // Andaman & Nicobar, Lakshadweep -> specific supernumerary allocations in NITs
  if ((normalizedCandidate.includes('andaman') || normalizedCandidate.includes('lakshadweep')) && normalizedNitState === 'pondicherry') {
    return 'Home State (HS)';
  }

  return 'Other State (OS)';
}
